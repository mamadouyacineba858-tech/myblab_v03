const round = (value) => Math.round(value * 100) / 100

function dot(line, column, dotColumn, dotRow) {
  const x = round(CELL_ORIGIN_X + column * CELL_PITCH_X + dotColumn * DOT_PITCH_X)
  const y = round(LINE_TOP_Y[line] + dotRow * DOT_PITCH_Y)
  return `M${x} ${y}h${DOT_WIDTH}v${DOT_HEIGHT}h-${DOT_WIDTH}z`
}

/** Un seul chemin (syntaxe path CSS) pour tous les points allumés des 32 cellules (aucun état React). */
function glyphPath(codes) {
  let d = ''
  codes.forEach((row, line) => row.forEach((code, column) => {
    const glyph = GLYPHS[code]
    if (!glyph) return
    glyph.forEach((bits, dotColumn) => {
      for (let dotRow = 0; dotRow < 7; dotRow++) if (bits & (1 << dotRow)) d += dot(line, column, dotColumn, dotRow)
    })
  }))
  return d
}

const cursorPath = ({ line, column }) => [0, 1, 2, 3, 4].map((dotColumn) => dot(line, column, dotColumn, CURSOR_ROW)).join('')

/**
 * Corps = raster CSA RUNTIME-V2 FROZEN (PCB, cadre, fenêtre, header 16 pastilles, aucun caractère).
 * Les caractères sont une projection de l'état runtime ST7066U (prop `lcd`, Visual State Registry) :
 * displayOn=false n'affiche rien ; le curseur souligné suit `cursorOn`. Le bit de clignotement est
 * conservé (data-blink) sans horloge visuelle propre. Aucune DDRAM, aucune logique électrique ici.
 */
export function LcdWh1602bPart({ lcd } = {}) {
  const { width, height } = getComponentDef('LCD_16X2_WH1602B')
  const displayOn = lcd?.displayOn === true
  const glyphs = displayOn ? glyphPath(lcd.codes) : ''
  const cursor = displayOn && lcd.cursorOn && lcd.cursor ? cursorPath(lcd.cursor) : ''
  return (
    <div
      className="part-lcd-wh1602b"
      aria-label="LCD 16x2 WH1602B"
      data-display-on={displayOn ? 'true' : 'false'}
      data-line-1={displayOn ? lcd.lines[0] : ''}
      data-line-2={displayOn ? lcd.lines[1] : ''}
      data-cursor={lcd?.cursorOn ? 'true' : 'false'}
      data-blink={lcd?.blinkOn ? 'true' : 'false'}
      style={{ position: 'relative', width, height }}
    >
      <picture>
        <source type="image/webp" srcSet={`${BASE}.1x.webp 1x, ${BASE}.3x.webp 3x`} />
        <img
          src={`${BASE}.1x.png`}
          srcSet={`${BASE}.1x.png 1x, ${BASE}.3x.png 3x`}
          width={width}
          height={height}
          draggable={false}
          alt=""
          aria-hidden={true}
          style={{ width: '100%', height: '100%', objectFit: 'contain', display: 'block', pointerEvents: 'none' }}
        />
      </picture>
      <div
        className="part-lcd-wh1602b__characters"
        aria-hidden={true}
        style={{ position: 'absolute', left: 0, top: 0, width, height, pointerEvents: 'none' }}
      >
        {glyphs && <div className="part-lcd-wh1602b__glyphs" data-dots={glyphs} style={dotLayerStyle(glyphs, width, height)} />}
        {cursor && <div className="part-lcd-wh1602b__cursor" data-dots={cursor} style={dotLayerStyle(cursor, width, height)} />}
      </div>
    </div>
  )
}

/** Calque de points : aplat d'encre découpé au chemin des points allumés (clip-path CSS, repère 1x). */
function dotLayerStyle(dots, width, height) {
  return { position: 'absolute', left: 0, top: 0, width, height, background: DOT_FILL, opacity: 0.88, clipPath: `path('${dots}')`, pointerEvents: 'none' }
}
